//! Win chance by minute from the game state: objectives.zig's "+ objectives held" model
//! (gold and XP lead, towers, inhibitors down, dragons, soul, elder, grubs, herald,
//! baron) fitted at every minute by `meiolol winchance`, which writes the weights to
//! winchance_weights.zig. Your games' turning minute and death cost read it.
//! Descriptive, not causal: the state misses what teams do with it.

const std = @import("std");
const store = @import("store");
const timeline = @import("riot/timeline.zig");
const objectives = @import("objectives.zig");
const logreg = @import("logreg.zig");
const stats = @import("stats.zig");
const weights = @import("winchance_weights.zig");
const Io = std.Io;

pub const feats = objectives.lead ++ objectives.held;
const dims = 1 + feats.len;
/// Later minutes reuse the last one's weights: too few games still going to fit them
pub const max_minute = 40;
/// Early surrenders (a leaver, mostly) and aborts end games before the state means much
const min_duration_s = 15 * 60;
const l2 = 1;

comptime {
    for (weights.w) |w| std.debug.assert(w.len == dims);
}

/// Blue's chance to win from the state at frame `minute`; 0.5 at the start, null once
/// the game has ended by then
pub fn blue(t: timeline.Timeline, minute: u8) ?f64 {
    if (minute == 0) return 0.5;
    if (weights.w.len == 0) return null;
    const s = objectives.stateAt(t, minute) orelse return null;
    return logreg.sigmoid(linear(weights.w[@min(minute, weights.w.len) - 1], s));
}

fn linear(w: [dims]f64, s: objectives.State) f64 {
    var x = w[0];
    for (feats, w[1..]) |f, b| x += b * s[@backingInt(f)];
    return x;
}

const Sample = struct { s: objectives.State, y: f32, test_row: bool };

/// Fits every minute on the ranked solo games with timelines in `db`, writes the weights
/// as Zig source to `src_out` and a held-out check (every fifth game by match id) to `w`
pub fn fit(gpa: std.mem.Allocator, db: store.Db, src_out: *Io.Writer, w: *Io.Writer) !void {
    var per_minute: [max_minute]std.ArrayList(Sample) = @splat(.empty);
    defer for (&per_minute) |*l| l.deinit(gpa);

    var q = try db.prepare(
        \\SELECT m.match_id, m.winning_team, t.data
        \\FROM matches m JOIN timeline.timelines t USING (match_id)
        \\WHERE m.queue_id = ? AND m.remake = 0 AND m.winning_team IS NOT NULL
        \\  AND m.duration_s >= ?
    );
    defer q.deinit();
    try q.bind(.{ stats.ranked_solo, min_duration_s });
    var scratch_state: std.heap.ArenaAllocator = .init(gpa);
    defer scratch_state.deinit();
    var games: usize = 0;
    while (try q.step()) {
        _ = scratch_state.reset(.retain_capacity);
        const scratch = scratch_state.allocator();
        const t = timeline.decode(scratch, store.raw.decompress(scratch, q.bytes(2)) catch continue) catch continue;
        const y: f32 = if (q.int(1) == 100) 1 else 0;
        const test_row = stats.matchKey(q.bytes(0)) % 5 == 0;
        games += 1;
        for (&per_minute, 1..) |*l, m| {
            const s = objectives.stateAt(t, @intCast(m)) orelse break;
            try l.append(gpa, .{ .s = s, .y = y, .test_row = test_row });
        }
    }

    try w.print("# meiolol winchance\n\n{d} ranked solo games of 15 min or more. Test: every " ++
        "fifth game by match id. Log loss in nats per game at that minute, from the train " ++
        "win rate and from the model; calibration: mean predicted vs actual blue win rate " ++
        "of test games with a predicted chance under 30% and over 70%.\n\n" ++
        "| minute | train | test | base | model | under 30%: pred / actual | over 70%: pred / actual |\n" ++
        "| --- | --- | --- | --- | --- | --- | --- |\n", .{games});
    try src_out.print(
        \\//! Generated by `meiolol winchance` ({d} games); see winchance.zig. Per minute from
        \\//! 1: intercept, then one weight per winchance.feats entry
        \\
        \\pub const w = [_][{d}]f64{{
        \\
    , .{ games, dims });

    var rows: std.ArrayList(logreg.Row) = .empty;
    defer rows.deinit(gpa);
    for (per_minute, 1..) |l, m| {
        rows.clearRetainingCapacity();
        var rate: f64 = 0;
        for (l.items) |x| if (!x.test_row) {
            try rows.append(gpa, row(x.s, x.y));
            rate += x.y;
        };
        if (rows.items.len < 1000) break;
        rate /= @floatFromInt(rows.items.len);
        const wt = try logreg.fit(gpa, dims, rows.items, l2);
        defer gpa.free(wt);

        var n_test: usize = 0;
        var base: f64 = 0;
        var model: f64 = 0;
        var low: [3]f64 = @splat(0);
        var high: [3]f64 = @splat(0);
        for (l.items) |x| if (x.test_row) {
            const p = logreg.sigmoid(linear(wt[0..dims].*, x.s));
            n_test += 1;
            base += logLoss(rate, x.y);
            model += logLoss(p, x.y);
            const bin = if (p < 0.3) &low else if (p > 0.7) &high else continue;
            bin.* = .{ bin[0] + p, bin[1] + x.y, bin[2] + 1 };
        };
        const n: f64 = @floatFromInt(@max(n_test, 1));
        try w.print("| {d} | {d} | {d} | {d:.3} | {d:.3} | {f} | {f} |\n", .{
            m,           rows.items.len, n_test, base / n, model / n,
            calib(&low), calib(&high),
        });
        try src_out.writeAll("    .{");
        for (wt, 0..) |b, i| try src_out.print("{s}{d:.6}", .{ if (i == 0) " " else ", ", b });
        try src_out.writeAll(" },\n");
    }
    try src_out.writeAll("};\n");
}

fn row(s: objectives.State, y: f32) logreg.Row {
    var r: logreg.Row = .{ .y = y };
    r.add(0, 1);
    for (feats, 1..) |f, i| r.add(@intCast(i), s[@backingInt(f)]);
    return r;
}

fn logLoss(p: f64, y: f64) f64 {
    const q = std.math.clamp(p, 1e-6, 1 - 1e-6);
    return -(y * @log(q) + (1 - y) * @log(1 - q));
}

/// "21% / 23% (n 1234)" for a bin of [sum predicted, sum actual, count]
fn calib(bin: *const [3]f64) Calib {
    return .{ .bin = bin.* };
}

const Calib = struct {
    bin: [3]f64,

    pub fn format(c: Calib, w: *Io.Writer) Io.Writer.Error!void {
        if (c.bin[2] == 0) return w.writeAll("-");
        try w.print("{d:.0}% / {d:.0}% (n {d:.0})", .{ 100 * c.bin[0] / c.bin[2], 100 * c.bin[1] / c.bin[2], c.bin[2] });
    }
};

test "blue's chance is a half at the start and moves with the state" {
    const arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    var a = arena_state;
    defer a.deinit();
    const arena = a.allocator();
    const raw = try store.raw.decompress(arena, @embedFile("riot/testdata/timeline.json.gz"));
    const t = try timeline.fromJson(arena, raw);
    try std.testing.expectEqual(@as(?f64, 0.5), blue(t, 0));
    if (weights.w.len == 0) return;
    const p = blue(t, 10).?;
    try std.testing.expect(p > 0 and p < 1);
    try std.testing.expect(blue(t, @intCast(t.frames.len)) == null);
}
