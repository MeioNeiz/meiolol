//! Build tool: `assetnames OUT [NAME FILE]...` writes a Zig file with each file's 8 hex
//! digits of FNV-1a under NAME, for site/assets.zig's hashed names. Hashing megabytes at
//! comptime cost minutes per compile of the backend
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len < 2 or args.len % 2 != 0) return error.Usage;
    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(a, "//! Generated by src/tools/assetnames.zig\n");
    var i: usize = 2;
    while (i < args.len) : (i += 2) {
        const data = try std.Io.Dir.cwd().readFileAlloc(io, args[i + 1], a, .unlimited);
        try out.print(a, "pub const @\"{s}\" = \"{x:0>8}\";\n", .{ args[i], std.hash.Fnv1a_32.hash(data) });
    }
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[1], .data = out.items });
}
